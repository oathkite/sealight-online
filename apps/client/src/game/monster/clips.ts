import type { Clip, Key, Track } from "@sealight/engine";

/*
 * モンスターの動き（24fps）。回転の軸は x が右、y が上、z が正面で、node の付け根を中心に回る。
 * 位置は元の位置からのずれ、大きさは倍率
 */

const FPS = 24;
const TAU = Math.PI * 2;

const track = (node: string, channel: Track["channel"], keys: readonly Key[]): Track => ({ node, channel, keys });
const clip = (name: string, frames: number, tracks: readonly Track[]): Clip => ({ name, fps: FPS, frames, loop: true, tracks });

/** 左右の耳。左（+x）の耳の z 回転を反転させて右の耳に使う */
const ears = (keys: readonly Key[]): readonly Track[] => [
  track("ear_l", "rotation", keys),
  track("ear_r", "rotation", keys.map(([f, x, y, z]) => [f, x, -y, -z] as const)),
];
const eyes = (keys: readonly Key[]): readonly Track[] => [track("eye_l", "scale", keys), track("eye_r", "scale", keys)];

/** 待機。呼吸、耳と尻尾のゆれ、まばたき */
const idle = clip("idle", 48, [
  track("body", "scale", [[0, 1, 1, 1], [24, 1.035, 0.955, 1.035], [48, 1, 1, 1]]),
  track("ear_l", "rotation", [[0, 0, 0, 0], [12, 0, 0, -0.14], [24, 0, 0, 0], [48, 0, 0, 0]]),
  track("ear_r", "rotation", [[0, 0, 0, 0], [24, 0, 0, 0], [36, 0, 0, 0.14], [48, 0, 0, 0]]),
  track("tail", "rotation", [[0, 0, -0.35, 0], [12, 0, 0.35, 0], [24, 0, -0.35, 0], [36, 0, 0.35, 0], [48, 0, -0.35, 0]]),
  ...eyes([[0, 1, 1, 1], [31, 1, 1, 1], [32, 1, 0.12, 1], [34, 1, 0.12, 1], [35, 1, 1, 1], [48, 1, 1, 1]]),
]);

/** 跳ねて歩く。着地でつぶれ、跳ぶ前に伸びる */
const hop = clip("hop", 12, [
  track("root", "position", [[0, 0, 0, 0], [2, 0, 0.05, 0], [6, 0, 0.25, 0], [10, 0, 0.05, 0], [12, 0, 0, 0]]),
  track("body", "scale", [[0, 1.14, 0.84, 1.14], [2, 0.92, 1.12, 0.92], [6, 1, 1, 1], [10, 0.95, 1.06, 0.95], [12, 1.14, 0.84, 1.14]]),
  ...ears([[0, 0, 0, -0.35], [6, 0, 0, 0.15], [12, 0, 0, -0.35]]),
  track("foot_l", "rotation", [[0, 0, 0, 0], [6, 0.6, 0, 0], [12, 0, 0, 0]]),
  track("foot_r", "rotation", [[0, 0, 0, 0], [6, -0.6, 0, 0], [12, 0, 0, 0]]),
  track("tail", "rotation", [[0, 0, 0, 0], [6, 0.5, 0, 0], [12, 0, 0, 0]]),
]);

/** しょんぼり。うつむいて耳が垂れ、目は半分閉じ、ゆっくり息をする */
const droop = clip("droop", 72, [
  track("body", "rotation", [[0, 0.18, 0, 0.07], [36, 0.22, 0, 0.1], [72, 0.18, 0, 0.07]]),
  track("body", "scale", [[0, 1.04, 0.93, 1.04], [36, 1.06, 0.9, 1.06], [72, 1.04, 0.93, 1.04]]),
  ...ears([[0, 0.5, 0, -0.9], [36, 0.55, 0, -1.0], [72, 0.5, 0, -0.9]]),
  ...eyes([[0, 1, 0.5, 1], [54, 1, 0.5, 1], [56, 1, 0.12, 1], [59, 1, 0.12, 1], [61, 1, 0.5, 1], [72, 1, 0.5, 1]]),
  track("tail", "rotation", [[0, -0.6, 0, 0], [72, -0.6, 0, 0]]),
]);

/** 喜ぶ。つぶれてから大きく跳び、くるっと 1 回転。目はにっこり。回り終えたら正面に戻す（1 回転は同じ向き） */
const cheer = clip("cheer", 30, [
  track("root", "position", [[0, 0, 0, 0], [3, 0, 0, 0], [10, 0, 0.52, 0], [17, 0, 0, 0], [22, 0, 0.12, 0], [26, 0, 0, 0], [30, 0, 0, 0]]),
  track("root", "rotation", [[0, 0, 0, 0], [3, 0, 0, 0], [16.99, 0, TAU, 0], [17, 0, 0, 0], [30, 0, 0, 0]]),
  track("body", "scale", [[0, 1, 1, 1], [3, 1.2, 0.78, 1.2], [6, 0.88, 1.18, 0.88], [10, 1, 1, 1], [17, 1.16, 0.82, 1.16], [21, 1, 1, 1], [30, 1, 1, 1]]),
  ...ears([[0, 0, 0, 0], [10, 0, 0, 0.3], [17, 0, 0, -0.4], [23, 0, 0, 0.15], [30, 0, 0, 0]]),
  ...eyes([[0, 1, 1, 1], [3, 1.1, 0.3, 1], [26, 1.1, 0.3, 1], [30, 1, 1, 1]]),
]);

/** 眠る。目を閉じて低く丸まり、ゆっくり大きく息をする */
const sleep = clip("sleep", 96, [
  track("body", "scale", [[0, 1.1, 0.84, 1.1], [48, 1.14, 0.8, 1.14], [96, 1.1, 0.84, 1.1]]),
  track("body", "rotation", [[0, 0.1, 0, 0.12], [96, 0.1, 0, 0.12]]),
  ...eyes([[0, 1.1, 0.08, 1], [96, 1.1, 0.08, 1]]),
  ...ears([[0, 0.3, 0, -0.7], [96, 0.3, 0, -0.7]]),
  track("tail", "rotation", [[0, -0.3, 0.9, 0], [48, -0.3, 1.0, 0], [96, -0.3, 0.9, 0]]),
]);

export const CLIPS = { idle, hop, droop, cheer, sleep } as const;
